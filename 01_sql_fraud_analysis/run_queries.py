"""Run every named block in queries.sql against fraud.db and write results.md.
Usage: python3 run_queries.py
"""
import re
import sqlite3
import pandas as pd
from pathlib import Path

here = Path(__file__).parent
db = here.parent / "data" / "fraud.db"
sql_text = (here / "queries.sql").read_text()

blocks = re.split(r"^-- name: ", sql_text, flags=re.M)[1:]
con = sqlite3.connect(db)
out = ["# Project 1 results (auto-generated by run_queries.py)\n"]
for b in blocks:
    name, _, body = b.partition("\n")
    question = next((l[3:] for l in body.splitlines() if l.startswith("-- Q")), "")
    df = pd.read_sql_query(body, con)
    print(f"\n=== {name.strip()} ===")
    print(df.to_string(index=False))
    out.append(f"## {name.strip()}\n\n{question}\n\n{df.to_markdown(index=False)}\n")
(here / "results.md").write_text("\n".join(out))
print("\nwrote results.md")
